# エピソードデータとラベルをまとめる
episodes = [epi_005, epi_030, epi_060, epi_090, epi_125, epi_135]
episode_labels = ['Episode 005', 'Episode 030', 'Episode 060', 'Episode 090', 'Episode 125', 'Episode 135']
colors = ['blue', 'orange', 'green', 'red', 'purple', 'brown']

# 全データの範囲を計算（軸の範囲設定用）
all_data = np.vstack(episodes)
x_min, x_max = all_data[:, 0].min() * 0.9, all_data[:, 0].max() * 1.1
y_min, y_max = all_data[:, 1].min() * 0.9, all_data[:, 1].max() * 1.1

# アニメーション用の図とaxの設定
fig, ax = plt.subplots(figsize=(12, 8))

def animate(frame):
    ax.clear()
    
    # 現在のフレームまでのエピソードを表示
    for i in range(frame + 1):
        alpha = 0.3 if i < frame else 1.0  # 過去のエピソードは薄く表示
        size = 30 if i < frame else 80      # 現在のエピソードは大きく表示
        
        ax.scatter(episodes[i][:, 0], episodes[i][:, 1], 
                  alpha=alpha, label=episode_labels[i], 
                  s=size, c=colors[i])
    
    # 軸の設定
    ax.set_xlim(x_min, x_max)
    ax.set_ylim(y_min, y_max)
    ax.set_xlabel('目的関数1 (Objective 1)', fontsize=12)
    ax.set_ylabel('目的関数2 (Objective 2)', fontsize=12)
    ax.set_title(f'Paretoフロントの進化 - {episode_labels[frame]}', fontsize=14)
    ax.legend(loc='upper right')
    ax.grid(True, alpha=0.3)

# アニメーションの作成
anim = animation.FuncAnimation(fig, animate, frames=len(episodes), 
                             interval=2000, repeat=True, blit=False)

# GIFとして保存
print("GIFアニメーションを生成中...")
anim.save('pareto_animation_pcn.gif', writer='pillow', fps=0.5, dpi=100)
print("GIFアニメーションが 'pareto_animation_pcn.gif' として保存されました！")

